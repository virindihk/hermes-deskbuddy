  const SUPPORTED_LOCALES = Object.freeze(Object.keys(I18N));

  /**
   * @param {unknown} locale
   * @returns {string}
   */
  function normalizeLocale(locale) {
    return SUPPORTED_LOCALES.includes(String(locale)) ? String(locale) : 'zh';
  }

  /**
   * @param {unknown} locale
   * @param {string} key
   * @param {Record<string, string | number>} [vars]
   * @returns {string}
   */
  function t(locale, key, vars = {}) {
    const normalizedLocale = normalizeLocale(locale);
    const dict = I18N[normalizedLocale] || I18N.zh;
    let text = dict[key] !== undefined ? dict[key] : I18N.zh[key] !== undefined ? I18N.zh[key] : key;
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(new RegExp(`{${k}}`, 'g'), String(v));
    }
    return text;
  }

  return {
    I18N,
    SUPPORTED_LOCALES,
    normalizeLocale,
    t,
  };
